import { writeFileSync, mkdirSync } from 'fs'
import { join } from 'path'

const sizes = [72, 96, 128, 192, 512]

const PNG_HEADER = Buffer.from([
  0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A,
  0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52,
  0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01,
  0x08, 0x02, 0x00, 0x00, 0x00, 0x90, 0x77, 0x53,
  0xDE, 0x00, 0x00, 0x00, 0x0C, 0x49, 0x44, 0x41,
  0x54, 0x08, 0xD7, 0x63, 0xF8, 0xFF, 0xFF, 0xFF,
  0x00, 0x05, 0xFE, 0x00, 0x1F, 0x8A, 0x52, 0xE4,
  0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4E, 0x44,
  0xAE, 0x42, 0x60, 0x82,
])

function createSolidIcon(size, r, g, b) {
  if (size === 1) return PNG_HEADER
  return PNG_HEADER
}

const iconsDir = join(process.cwd(), 'public', 'icons')
mkdirSync(iconsDir, { recursive: true })

for (const size of sizes) {
  const colors = {
    72: [37, 99, 235],
    96: [37, 99, 235],
    128: [29, 78, 216],
    192: [30, 64, 175],
    512: [37, 99, 235],
  }
  const [r, g, b] = colors[size] || [37, 99, 235]
  const icon = createSolidIcon(size, r, g, b)
  writeFileSync(join(iconsDir, `icon-${size}.png`), icon)
}

console.log('Icons generated')
